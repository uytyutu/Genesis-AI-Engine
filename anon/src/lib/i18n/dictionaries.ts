/**
 * Translate with chain: locale → ru → en → "…"
 * Never returns raw keys. Dev warns on missing locale entry.
 */
export function t(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const primary = DICTS[locale]?.[key];
  const fallbackRu = DICTS.ru?.[key];
  const fallbackEn = DICTS.en?.[key];
  let value = primary ?? fallbackRu ?? fallbackEn;
  if (value == null) {
    if (process.env.NODE_ENV === "development") {
      console.warn(`[MISSING_TRANSLATION] locale=${locale} key=${key}`);
    }
    value = MISSING;
  } else if (primary == null && process.env.NODE_ENV === "development") {
    console.warn(`[MISSING_TRANSLATION] locale=${locale} key=${key}`);
  }
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      value = value.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return value;
}

export function allDictKeys(): string[] {
  return Object.keys(en);
}

export function dictCoverage(locale: Locale): { total: number; present: number; missing: string[] } {
  const keys = allDictKeys();
  const missing: string[] = [];
  let present = 0;
  const complete = locale === "en" || locale === "de" || locale === "ru" || locale === "uk";
  const overlay = !complete
    ? EXTRA_LOCALES[locale as keyof typeof EXTRA_LOCALES] || {}
    : null;
  for (const key of keys) {
    if (complete) {
      if (DICTS[locale]?.[key] != null || DICTS.ru?.[key] != null) present += 1;
      else missing.push(key);
      continue;
    }
    // Extra locales: native overlay counts as present; ru-merge fills the rest (fallback).
    if (overlay?.[key] != null) present += 1;
    else missing.push(key);
  }
  return { total: keys.length, present, missing };
}

