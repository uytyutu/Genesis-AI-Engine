def list_compositions() -> list[CompositionConcept]:
    return list(COMPOSITION_LIBRARY.values())


def get_composition(composition_id: str) -> CompositionConcept | None:
    return COMPOSITION_LIBRARY.get((composition_id or "").strip().lower())


def compositions_for_niche(niche_id: str | None, *, premium: bool = True) -> list[CompositionConcept]:
    niche = (niche_id or "generic").strip().lower()
    scored: list[tuple[int, CompositionConcept]] = []
    for c in COMPOSITION_LIBRARY.values():
        score = 0
        if niche in c.niche_affinity:
            score += 10
        if premium and c.anti_predictable:
            score += 4
        if premium and not c.anti_predictable:
            score -= 6
        if niche == "psychology" and c.id in (
            "sanctuary",
            "garden",
            "whisper",
            "storytelling",
            "chamber",
            "cinematic",
            "magazine",
            "ritual",
            "horizon",
            "manifesto",
            "breath",
            "solstice",
            "floating",
            "narrative",
            "cascade",
            "spotlight",
            "nature",
            "atelier_night",
        ):
            score += 5
        scored.append((score, c))
    scored.sort(key=lambda x: (-x[0], x[1].id))
    return [c for _, c in scored]


def is_predictable_funnel(section_order: tuple[str, ...] | list[str]) -> bool:
    """True when the page reads as Hero → text/cards ladder."""
    keys = [k for k in section_order if k]
    if len(keys) < 4:
        return False
    head = tuple(keys[:5])
    for boring in _BORING_PREFIXES:
        if head[: len(boring)] == boring:
            return True
    # Three+ consecutive cardy blocks = section stack
    run = 0
    for k in keys:
        if k in CARDY_SECTIONS:
            run += 1
            if run >= 3:
                return True
        else:
            run = 0
    return False


def rhythm_signature(section_order: tuple[str, ...] | list[str]) -> str:
    """Compact signature for anti-clone / diversity."""
    return ">".join(section_order[:12])
