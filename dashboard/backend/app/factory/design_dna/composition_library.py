"""Composition Library — selects Renderer Approach / Strategy (DOM architecture).

Field ``section_order`` remains for ClassicRenderer only.
Named Strategies own their HTML trees.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any


@dataclass(frozen=True)
class CompositionConcept:
    """One complete page composition — a designer choice, not a shuffle."""

    id: str
    label: str
    section_order: tuple[str, ...]
    hero_layouts: tuple[str, ...]
    component: str  # A|B|C
    layout_seed: str  # preferred L-profile family
    niche_affinity: tuple[str, ...]  # niches that love this form
    anti_predictable: bool = True  # True = breaks classic funnel rhythm
    mood: str = ""
    notes: str = ""

    def as_dict(self) -> dict[str, Any]:
        from app.factory.renderers.registry import (
            COMPOSITION_TO_APPROACH,
            COMPOSITION_TO_STRATEGY,
        )

        approach = COMPOSITION_TO_APPROACH.get(self.id, "")
        return {
            "id": self.id,
            "label": self.label,
            "section_order": list(self.section_order),
            "hero_layouts": list(self.hero_layouts),
            "component": self.component,
            "layout_seed": self.layout_seed,
            "niche_affinity": list(self.niche_affinity),
            "anti_predictable": self.anti_predictable,
            "mood": self.mood,
            "notes": self.notes,
            "approach": approach,
            "renderer_strategy": COMPOSITION_TO_STRATEGY.get(self.id, "")
            or approach,
        }


